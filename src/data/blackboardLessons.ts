export function getLessonsBySubject(subjectName: string): BlackboardLesson[] {
  return INITIAL_BLACKBOARD_LESSONS.filter(
    lesson => lesson.subject.toLowerCase().includes(subjectName.toLowerCase()) ||
              subjectName.toLowerCase().includes(lesson.subject.toLowerCase())
  );
}

export function getAllSubjectsInBank(): string[] {
  const set = new Set<string>();
  INITIAL_BLACKBOARD_LESSONS.forEach(l => set.add(l.subject));
  return Array.from(set);
}
