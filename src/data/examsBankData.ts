const SOLVED_STORAGE_KEY = 'dzexams_solved_list_v1';

export function getSolvedExamIds(): Set<string> {
  try {
    const raw = localStorage.getItem(SOLVED_STORAGE_KEY);
    if (raw) {
      const arr = JSON.parse(raw);
      if (Array.isArray(arr)) return new Set(arr);
    }
  } catch (e) {
    console.warn('Could not read solved exams from storage:', e);
  }
  return new Set();
}

export function saveSolvedExamId(examId: string): void {
  try {
    const set = getSolvedExamIds();
    set.add(examId);
    localStorage.setItem(SOLVED_STORAGE_KEY, JSON.stringify(Array.from(set)));
  } catch (e) {
    console.warn('Could not save solved exam ID:', e);
  }
}

