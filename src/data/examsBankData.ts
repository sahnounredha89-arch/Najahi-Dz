// Generate an exact bank of 20 exams for the selected subject, grade and term
export function generateExamsForSubject(
  subjectName: string,
  gradeId: string,
  cycle: 'primary' | 'middle' | 'secondary' | 'university',
  gradeLabel: string,
  termFilter: 'all' | 't1' | 't2' | 't3' | 'official' = 'all',
  totalCount: number = 20
): ExamModel[] {
  const solvedSet = getSolvedExamIds();
  const exams: ExamModel[] = [];

  const termOptions: { id: 't1' | 't2' | 't3' | 'official'; label: string }[] = [
    { id: 't1', label: 'الفصل الأول' },
    { id: 't2', label: 'الفصل الثاني' },
    { id: 't3', label: 'الفصل الثالث' },
    { id: 'official', label: cycle === 'secondary' ? 'امتحان تجريبي (BAC Blanc)' : cycle === 'middle' ? 'امتحان تجريبي (BEM Blanc)' : 'امتحان رسمي معتمد' },
  ];

  for (let i = 1; i <= totalCount; i++) {
    // If term filter is specified, use it, else distribute across terms
    let selectedTerm = termOptions[(i - 1) % termOptions.length];
    if (termFilter !== 'all') {
      const match = termOptions.find(t => t.id === termFilter);
      if (match) selectedTerm = match;
    }

    const examId = `exam-${subjectName}-${gradeId}-${selectedTerm.id}-${i}`.replace(/\s+/g, '_');
    const isSolved = solvedSet.has(examId);

    const institution = ALGERIAN_INSTITUTIONS[(i - 1) % ALGERIAN_INSTITUTIONS.length];
    const dua = RESPECTFUL_CLOSINGS[(i - 1) % RESPECTFUL_CLOSINGS.length];
    const year = i % 2 === 0 ? '2023/2024' : '2022/2023';
    const duration = cycle === 'secondary' ? '02 سا 00 د' : cycle === 'middle' ? '01 سا 30 د' : '01 سا 00 د';
    const coefficient = cycle === 'secondary' ? 5 : cycle === 'middle' ? 3 : 2;

    const { exercises, situation } = buildExercisesForSubject(
      subjectName,
      i,
      selectedTerm.label,
      gradeId
    );

    exams.push({
      id: examId,
      subject: subjectName,
      cycle,
      gradeId,
      gradeLabel,
      term: selectedTerm.id,
      termLabel: selectedTerm.label,
      examNumber: i,
      title: `امتحان ${subjectName} الرسمي - نموذج رقم (${i}) [${selectedTerm.label}]`,
      institution,
      year,
      duration,
      coefficient,
      totalScore: 20,
      exercises,
      integratedSituation: situation,
      isSolved,
      duaText: dua.text,
      duaRef: dua.ref,
    });
  }

  return exams;
}

